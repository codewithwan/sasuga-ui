#!/usr/bin/env python3
"""Writes apps/docs/src/data/art.ts: the size and a tiny placeholder for every image in
apps/docs/public/assets (plus the social card, an opaque image for the docs demo), for <ImageLoader>.

Cut-out art (with transparency) gets a 'shape' placeholder: its silhouette as a 32 px alpha
mask, which the loader fills with the theme tint while the file downloads. Opaque images get a
'blur' placeholder: a 16 px preview the loader blurs.

    python3 scripts/art-placeholders.py        (needs Pillow: pip install pillow)
"""
import base64
import io
from pathlib import Path

from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / 'apps/docs/public/assets'
OUT = ROOT / 'apps/docs/src/data/art.ts'
EXTS = {'.webp', '.png', '.jpg', '.jpeg', '.avif'}


def data_uri(im: Image.Image) -> str:
    buf = io.BytesIO()
    im.save(buf, 'PNG', optimize=True)
    return 'data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode()


def placeholder(path: Path):
    im = Image.open(path).convert('RGBA')
    w, h = im.size
    alpha = im.getchannel('A')
    cutout = alpha.getextrema()[0] < 250
    side = 32 if cutout else 16
    k = side / max(w, h)
    size = (max(1, round(w * k)), max(1, round(h * k)))
    if cutout:
        a = alpha.resize(size, Image.LANCZOS).filter(ImageFilter.GaussianBlur(0.4))
        mask = Image.new('RGBA', size, (0, 0, 0, 0))
        mask.putalpha(a)
        return w, h, 'shape', data_uri(mask)
    return w, h, 'blur', data_uri(im.convert('RGB').resize(size, Image.LANCZOS))


PUBLIC = ASSETS.parent
files = sorted(p for p in ASSETS.rglob('*') if p.suffix.lower() in EXTS) + [PUBLIC / 'og-image.png']
rows = []
for p in files:
    rel = p.relative_to(PUBLIC).as_posix()
    key = p.relative_to(ASSETS if p.is_relative_to(ASSETS) else PUBLIC).with_suffix('').as_posix()
    w, h, kind, uri = placeholder(p)
    rows.append(f"  '{key}': art('/{rel}', {w}, {h}, '{kind}', '{uri}'),")

OUT.write_text(
    """// Generated by scripts/art-placeholders.py from apps/docs/public/assets. Do not edit by hand.
import { withBase } from './site'

export type Art = { src: string; width: number; height: number; placeholderKind: 'shape' | 'blur'; placeholder: string }

const art = (path: string, width: number, height: number, placeholderKind: Art['placeholderKind'], placeholder: string): Art => ({
  src: withBase(path),
  width,
  height,
  placeholderKind,
  placeholder,
})

/** Every image under public/assets, keyed by its path without the extension (e.g. 'mascot/koma-happy'). */
export const ART = {
"""
    + '\n'.join(rows)
    + """
} as const

export type ArtName = keyof typeof ART
"""
)
print(f'{OUT.relative_to(ROOT)}: {len(rows)} images')
